"""Ask DeepSeek-V4.1-Flash a question about an image, on one 8-GPU node.

A wrapper around ``tasks/omni/infer_omni.py`` rather than a second inference
path: it builds the torchrun invocation, waits, and presents the reply. The
model runs at the precision the checkpoint was released in -- fp8 dense
weights, fp4 experts, fp8 n-gram tables -- sharded by expert and embed
parallelism across the eight ranks. Nothing is dequantized to bf16.

The reply is split on the reasoning marker. V4.1 thinks before it answers and
the closing ``</think>`` is generated, so a raw reply.txt begins with the
model's scratch work; the answer alone is what most callers want, and
``--show-reasoning`` brings the rest back.

Examples
--------

    python scripts/deepseek_v41/chat.py \\
        --image tests/testdata/qwen-vl-demo.jpeg \\
        --question "Describe this image in one sentence."

    python scripts/deepseek_v41/chat.py \\
        --image photo.jpg --question "What is written on the sign?" \\
        --show-reasoning
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time
from pathlib import Path
from typing import Sequence


REPO_ROOT = Path(__file__).resolve().parents[2]

DEFAULT_MODEL_PATH = "/mnt/hdfs/veomni/models/seed_omni/DeepSeek-V4.1-Flash"
BASE_CONFIG = "configs/seed_omni/DeepSeek/deepseek_v41_flash/train/base.yaml"
MODULES_CONFIG = "configs/seed_omni/DeepSeek/deepseek_v41_flash/infer/modules_infer_fsdp.yaml"

# Generated by the model, unlike the opening tag, which the chat template
# supplies as part of the assistant prefix. So the reply is [reasoning, answer]
# when it is present and a bare answer when it is not.
REASONING_MARKER = "</think>"


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Ask DeepSeek-V4.1-Flash about an image (8 GPUs, checkpoint precision).",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--image", required=True, help="Path or URL of the image to ask about.")
    parser.add_argument("--question", required=True, help="The question to ask about the image.")
    parser.add_argument("--model-path", default=DEFAULT_MODEL_PATH, help="Split-checkpoint root.")
    parser.add_argument(
        "--nproc",
        type=int,
        default=8,
        help="Ranks to launch. The shipped module config shards experts and tables 8 ways.",
    )
    parser.add_argument("--output-dir", default="/tmp/dsv41_chat", help="Where the reply and trace are written.")
    parser.add_argument("--show-reasoning", action="store_true", help="Print the model's scratch work too.")
    parser.add_argument("--show-log", action="store_true", help="Stream the run log instead of hiding it.")
    return parser.parse_args(argv)


def build_command(args: argparse.Namespace) -> list[str]:
    return [
        "torchrun",
        "--nnodes=1",
        f"--nproc-per-node={args.nproc}",
        "--node-rank=0",
        "--standalone",
        "tasks/omni/infer_omni.py",
        BASE_CONFIG,
        "--model.model_config.modules",
        MODULES_CONFIG,
        "--model.model_path",
        args.model_path,
        "--model.model_config.infer_type",
        "vision_understanding",
        "--infer.prompt",
        args.question,
        "--infer.images",
        args.image,
        "--infer.output_dir",
        args.output_dir,
    ]


def split_reply(reply: str) -> tuple[str, str]:
    """Return ``(reasoning, answer)``; reasoning is empty when the model did not think."""
    if REASONING_MARKER not in reply:
        return "", reply.strip()
    reasoning, _, answer = reply.partition(REASONING_MARKER)
    return reasoning.strip(), answer.strip()


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)

    # A missing image only surfaces after the checkpoint is loaded otherwise,
    # which is several minutes of reading 468 GB to reach a typo. URLs are left
    # to the image processor, which is what fetches them.
    if "://" not in args.image and not Path(args.image).is_file():
        print(f"[error] no such image: {args.image}", file=sys.stderr)
        return 2

    environ = dict(os.environ)
    environ.setdefault("TOKENIZERS_PARALLELISM", "false")
    environ.setdefault("TORCH_NCCL_AVOID_RECORD_STREAMS", "1")
    # The expert slabs are allocated and freed at wildly different sizes across
    # the 40 layers; without this the tail of a long prefill fragments.
    environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

    log_path = Path(args.output_dir) / "run.log"
    log_path.parent.mkdir(parents=True, exist_ok=True)

    print(f"[info] launching {args.nproc} ranks; loading the checkpoint takes a few minutes")
    print(f"[info] log: {log_path}")
    started = time.time()

    with log_path.open("w") as log:
        completed = subprocess.run(
            build_command(args),
            cwd=REPO_ROOT,
            env=environ,
            stdout=None if args.show_log else log,
            stderr=subprocess.STDOUT if args.show_log else log,
        )

    elapsed = time.time() - started
    if completed.returncode != 0:
        print(f"[error] the run failed after {elapsed:.0f}s; last lines of {log_path}:", file=sys.stderr)
        tail = log_path.read_text(errors="replace").splitlines()[-25:]
        print("\n".join(tail), file=sys.stderr)
        return completed.returncode

    reply_path = Path(args.output_dir) / "vision_understanding" / "reply.txt"
    if not reply_path.is_file():
        print(f"[error] the run finished but wrote no reply to {reply_path}", file=sys.stderr)
        return 1

    reasoning, answer = split_reply(reply_path.read_text())
    if args.show_reasoning and reasoning:
        print("\n--- reasoning ---")
        print(reasoning)
    print("\n--- answer ---")
    print(answer)
    print(f"\n[info] {elapsed:.0f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
